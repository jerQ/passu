def columns(art):
    """Five column bytes, bit 0 = top row (the SSD1306/SH1106 page order)."""
    rows = art.split("|")
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), art
    return [sum(1 << y for y in range(7) if rows[y][x] == "#") for x in range(5)]


def main():
    print("/* Generated by tools/gen_font.py - edit the glyphs there, not here.")
    print(" *")
    print(" * 5x7 glyphs in a 6x8 cell for printable ASCII 0x20-0x7E. Each glyph is")
    print(" * five column bytes, bit 0 = top row. Characters without their own glyph")
    print(" * use '?'. The glyphs were drawn for this project and are public domain. */")
    print("#pragma once")
    print()
    print("#include <stdint.h>")
    print()
    print("#define FONT_FIRST 0x20")
    print("#define FONT_LAST  0x7E")
    print()
    print("static const uint8_t font6x8[FONT_LAST - FONT_FIRST + 1][5] = {")
    for code in range(0x20, 0x7F):
        ch = chr(code)
        cols = columns(GLYPHS.get(ch, GLYPHS["?"]))
        label = ch if ch not in "\\" else "backslash"
        own = "" if ch in GLYPHS else " (as '?')"
        print("    { " + ", ".join(f"0x{c:02X}" for c in cols)
              + f" }},  /* 0x{code:02X} '{label}'{own} */")
    print("};")


if __name__ == "__main__":
    main()
